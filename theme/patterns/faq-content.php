<!-- wp:details -->
<details class="wp-block-details"><summary>What is the reStart?</summary>
<!-- wp:paragraph -->
<p>The reStart is a gift registry platform built for people rebuilding their lives after divorce. Whether you need a new toaster, a set of sheets, or a couch to call your own, the reStart makes it easy for the people who love you to help you start fresh.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is the reStart free?</summary>
<!-- wp:paragraph -->
<p>Yes. Creating an account and building a registry is completely free. We don't take a cut of purchases — all transactions happen directly between your gift-givers and the retailers you choose.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I create a registry?</summary>
<!-- wp:paragraph -->
<p>Create an account, then head to Start a Registry. You'll give your registry a name, add a short description, and start adding items from any retailer you like. The whole setup takes about five minutes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I add items to my registry?</summary>
<!-- wp:paragraph -->
<p>From your registry dashboard, paste in a link to any product from any online retailer. the reStart pulls in the product name, image, and price automatically. You can also add a note to let gift-givers know why you want it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Who can see my registry?</summary>
<!-- wp:paragraph -->
<p>By default, your registry is private — only people with your direct link can view it. You can switch it to public at any time from your registry settings, which makes it discoverable on the Find a Registry page.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I share my registry?</summary>
<!-- wp:paragraph -->
<p>Every registry has a unique link you can copy from your dashboard and share however you like — text, email, a group chat, or a note in a card.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do people buy things from my registry?</summary>
<!-- wp:paragraph -->
<p>When someone clicks an item on your registry, they're taken directly to the retailer to complete the purchase. the reStart doesn't handle payments. After purchasing, they can mark the item as purchased so others know it's taken care of.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if an item is marked purchased but never arrives?</summary>
<!-- wp:paragraph -->
<p>We recommend that gift-givers keep their order confirmation from the retailer. If something goes wrong with a delivery, the issue is between the buyer and the retailer — the reStart isn't part of the transaction. You can un-mark an item as purchased from your registry dashboard if needed.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I have more than one registry?</summary>
<!-- wp:paragraph -->
<p>Yes. You can create multiple registries — one for your new apartment, one for the home office you're finally setting up, whatever you need.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I edit my registry after it's published?</summary>
<!-- wp:paragraph -->
<p>Absolutely. You can add, remove, and reorder items at any time. Changes are reflected immediately.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I delete my account?</summary>
<!-- wp:paragraph -->
<p>You can request account deletion by emailing us at hello@the-reStart.com. We'll remove your account and all associated data within 30 days.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

